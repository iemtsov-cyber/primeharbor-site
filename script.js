const root = document.documentElement;
const menuToggle = document.querySelector('.menu-toggle');
const mobileMenu = document.querySelector('.mobile-menu');
const form = document.getElementById('contactForm');
const status = document.getElementById('form-status');
let language = 'en';
function updateMenuLabel() { menuToggle.setAttribute('aria-label', copy[language][mobileMenu.hidden ? 'aria.open' : 'aria.close']); }
function closeMenu(returnFocus = false) {
  mobileMenu.hidden = true;
  menuToggle.setAttribute('aria-expanded','false');
  updateMenuLabel();
  if(returnFocus) menuToggle.focus();
}
function setLanguage(lang) {
  language = copy[lang] ? lang : 'en';
  root.lang = language;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const value = copy[language][el.dataset.i18n];
    if(value !== undefined) el.innerHTML = value;
  });
  document.querySelectorAll('[data-aria]').forEach(el => el.setAttribute('aria-label',copy[language][el.dataset.aria]));
  document.querySelectorAll('.lang-btn').forEach(btn => {
    const active = btn.dataset.lang === language;
    btn.classList.toggle('active',active);
    btn.setAttribute('aria-pressed',String(active));
  });
  document.querySelector('meta[name="description"]').content = copy[language]['meta.description'];
  document.querySelector('meta[property="og:description"]').content = copy[language]['meta.description'];
  updateMenuLabel();
  if(!status.hidden) status.textContent = copy[language]['contact.sent'];
  try { localStorage.setItem('primeharbor-language',language); } catch {}
}
let preferred = navigator.language?.toLowerCase().startsWith('ru') ? 'ru' : 'en';
try { const saved = localStorage.getItem('primeharbor-language'); if(copy[saved]) preferred = saved; } catch {}
document.querySelectorAll('.lang-btn').forEach(btn => btn.addEventListener('click',()=>setLanguage(btn.dataset.lang)));
setLanguage(preferred);
document.getElementById('year').textContent = new Date().getFullYear();
menuToggle.addEventListener('click',()=>{
  mobileMenu.hidden = !mobileMenu.hidden;
  menuToggle.setAttribute('aria-expanded',String(!mobileMenu.hidden));
  updateMenuLabel();
});
document.addEventListener('keydown',event=>{if(event.key === 'Escape' && !mobileMenu.hidden) closeMenu(true);});
mobileMenu.querySelectorAll('a').forEach(a=>a.addEventListener('click',()=>{
  closeMenu();
  const target = document.querySelector(a.getAttribute('href'));
  if(target) { target.setAttribute('tabindex','-1'); target.focus({preventScroll:true}); }
}));
document.addEventListener('click',event=>{if(!mobileMenu.hidden && !mobileMenu.contains(event.target) && !menuToggle.contains(event.target)) closeMenu();});
document.addEventListener('focusin',event=>{if(!mobileMenu.hidden && !mobileMenu.contains(event.target) && !document.querySelector('.site-header').contains(event.target)) closeMenu();});
matchMedia('(min-width: 1101px)').addEventListener('change',event=>{if(event.matches) closeMenu();});
form.addEventListener('submit',event=>{
  event.preventDefault();
  if(!form.reportValidity()) return;
  const data = new FormData(form);
  const area = copy[language]['option.'+data.get('area')];
  const subject = 'Prime Harbor — '+ area;
  const body = [
    copy[language]['contact.name']+': '+data.get('name'),
    copy[language]['contact.company']+': '+data.get('company'),
    copy[language]['contact.email']+': '+data.get('email'),
    copy[language]['contact.area']+': '+area,
    '',data.get('message')
  ].join('\n');
  status.hidden = false;
  status.textContent = copy[language]['contact.sent'];
  window.location.href = 'mailto:contact@primeharbor.ru?subject='+encodeURIComponent(subject)+'&body='+encodeURIComponent(body);
});
